def ensure_default_faq():
    conn = get_db_connection()
    try:
        cursor = conn.cursor()
        cursor.execute('SELECT COUNT(*) FROM faq_articles')
        if cursor.fetchone()[0]:
            return
        category_order = {}
        article_order = {}
        for category_slug, category_title, title, blocks in DEFAULT_FAQ:
            if category_slug not in category_order:
                category_order[category_slug] = len(category_order) + 1
                article_order[category_slug] = 0
            article_order[category_slug] += 1
            cursor.execute('''
                INSERT INTO faq_articles
                (category_slug, category_title, title, blocks_json, category_order, sort_order)
                VALUES (?, ?, ?, ?, ?, ?)
            ''', (category_slug, category_title, title, json.dumps(blocks, ensure_ascii=False),
                  category_order[category_slug], article_order[category_slug]))
        conn.commit()
    finally:
        conn.close()


def get_faq_articles(include_unpublished=False):
    conn = get_db_connection()
    try:
        query = 'SELECT * FROM faq_articles'
        if not include_unpublished:
            query += ' WHERE is_published = 1'
        query += ' ORDER BY category_order, sort_order, id'
        cursor = conn.execute(query)
        names = [description[0] for description in cursor.description]
        result = []
        for row in cursor.fetchall():
            item = dict(zip(names, row))
            try:
                item['blocks'] = json.loads(item.pop('blocks_json') or '[]')
            except (TypeError, json.JSONDecodeError):
                item['blocks'] = []
            item['is_published'] = bool(item['is_published'])
            result.append(item)
        return result
    finally:
        conn.close()


def create_faq_article(data, user_id):
    conn = get_db_connection()
    try:
        cursor = conn.cursor()
        cursor.execute('''
            INSERT INTO faq_articles
            (category_slug, category_title, title, blocks_json, category_order, sort_order, is_published, updated_by)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        ''', (data['category_slug'], data['category_title'], data['title'],
              json.dumps(data.get('blocks', []), ensure_ascii=False), data.get('category_order', 1),
              data.get('sort_order', 1), 1 if data.get('is_published', True) else 0, user_id))
        conn.commit()
        return cursor.lastrowid
    finally:
        conn.close()


def update_faq_article(article_id, data, user_id):
    conn = get_db_connection()
    try:
        cursor = conn.cursor()
        cursor.execute('''
            UPDATE faq_articles SET category_slug = ?, category_title = ?, title = ?, blocks_json = ?,
                category_order = ?, sort_order = ?, is_published = ?, updated_by = ?,
                updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
        ''', (data['category_slug'], data['category_title'], data['title'],
              json.dumps(data.get('blocks', []), ensure_ascii=False), data.get('category_order', 1),
              data.get('sort_order', 1), 1 if data.get('is_published', True) else 0,
              user_id, article_id))
        conn.commit()
        return cursor.rowcount > 0
    finally:
        conn.close()


def delete_faq_article(article_id):
    conn = get_db_connection()
    try:
        cursor = conn.cursor()
        cursor.execute('DELETE FROM faq_articles WHERE id = ?', (article_id,))
        conn.commit()
        return cursor.rowcount > 0
    finally:
        conn.close()
